export function seedDatabase() {
  console.log('🌱 Seeding Oxford 3000 Database...');

  const insertWord = db.prepare(`
    INSERT INTO words (
      word, phonetic, cefr_level, part_of_speech, definition_en, definition_pl,
      example_en, example_pl, collocations, synonyms, antonyms, oxford_category,
      memory_hook, frequency_rank
    ) VALUES (
      ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?
    )
    ON CONFLICT(word) DO UPDATE SET
      phonetic = excluded.phonetic,
      cefr_level = excluded.cefr_level,
      part_of_speech = excluded.part_of_speech,
      definition_en = excluded.definition_en,
      definition_pl = excluded.definition_pl,
      example_en = excluded.example_en,
      example_pl = excluded.example_pl,
      collocations = excluded.collocations,
      synonyms = excluded.synonyms,
      antonyms = excluded.antonyms,
      oxford_category = excluded.oxford_category,
      memory_hook = excluded.memory_hook,
      frequency_rank = excluded.frequency_rank
  `);

  const insertProgress = db.prepare(`
    INSERT OR IGNORE INTO user_progress (word_id, state, repetitions, interval_days, ease_factor, next_review, streak_count, is_favorite)
    VALUES (?, 'new', 0, 0, 2.5, 0, 0, 0)
  `);

  const allSeedWords = [...oxfordWords, ...extendedOxfordWords];

  for (const w of allSeedWords) {
    insertWord.run(
      w.word,
      w.phonetic,
      w.cefr_level,
      w.part_of_speech,
      w.definition_en,
      w.definition_pl,
      w.example_en,
      w.example_pl,
      w.collocations,
      w.synonyms,
      w.antonyms,
      w.oxford_category,
      w.memory_hook,
      w.frequency_rank
    );
  }

  // Ensure user_progress rows exist for all words
  const allWords = db.prepare('SELECT id FROM words').all();
  for (const row of allWords) {
    insertProgress.run(row.id);
  }

  // Pre-seed a few into learning/review for an immediate dopamine feed experience
  const sampleReview = db.prepare(`
    UPDATE user_progress
    SET state = 'learning', repetitions = 1, interval_days = 1, next_review = ?, streak_count = 2, is_favorite = 1
    WHERE word_id = (SELECT id FROM words WHERE word = 'streak')
  `);
  sampleReview.run(Date.now() - 10000); // already due!

  const sampleReview2 = db.prepare(`
    UPDATE user_progress
    SET state = 'review', repetitions = 2, interval_days = 3, next_review = ?, streak_count = 3
    WHERE word_id = (SELECT id FROM words WHERE word = 'captivate')
  `);
  sampleReview2.run(Date.now() - 5000); // already due!

  console.log(`✅ Seeded ${allWords.length} Oxford 3000 entries into SQLite database.`);
}

